def _copy_cutoff_log_sheet(wb, all_res_ws) -> object:
	if "cutoff_log" in wb.sheetnames:
		del wb["cutoff_log"]
	ws = wb.copy_worksheet(wb["cutoff"])
	outlier_columns = [
		col
		for col in range(1, ws.max_column + 1)
		if normalize_temp_name(ws.cell(1, col).value).lower() in {"outlier", "outlier_log10"}
	]
	if not outlier_columns:
		raise ValueError("cutoff sheet is missing the Outlier column")
	outlier_col = outlier_columns[0]
	# Rebuild this field so no linear cutoff value can survive the worksheet copy.
	for col in reversed(outlier_columns):
		ws.delete_cols(col)
	ws.insert_cols(outlier_col)
	ws.cell(1, outlier_col, "Outlier_log10")
	for row in range(2, ws.max_row + 1):
		ws.cell(row, outlier_col, None)

	all_res_cols = header_column_map(all_res_ws)
	log10_lookup: Dict[str, object] = {}
	if "sample" in all_res_cols and "outlier_log10" in all_res_cols:
		for row in range(2, all_res_ws.max_row + 1):
			sample_key = canonical_lookup_key(all_res_ws.cell(row, all_res_cols["sample"]).value)
			value = all_res_ws.cell(row, all_res_cols["outlier_log10"]).value
			if sample_key and value not in (None, "") and sample_key not in log10_lookup:
				log10_lookup[sample_key] = value
	cutoff_cols = header_column_map(ws)
	for row in range(2, ws.max_row + 1):
		sample = canonical_lookup_key(ws.cell(row, cutoff_cols["sample"]).value)
		if sample in log10_lookup:
			ws.cell(row, outlier_col, log10_lookup[sample])
	return ws


