def _outlier_data_mode(value: object) -> Optional[str]:
	text = normalize_temp_name(value).lower().replace(" ", "")
	if "log10" in text or "log(s/p)" in text:
		return "log10"
	if "linear" in text or "s/p" in text:
		return "linear"
	return None


def build_outlier_lookups(outliers_ws) -> Tuple[Dict[str, float], Dict[str, float]]:
	linear_lookup: Dict[str, float] = {}
	log10_lookup: Dict[str, float] = {}
	column_modes: Dict[int, str] = {}
	global_modes: set[str] = set()
	for col in range(1, outliers_ws.max_column + 1):
		mode = _outlier_data_mode(outliers_ws.cell(1, col).value)
		if mode is not None:
			column_modes[col] = mode
			global_modes.add(mode)
	default_mode = next(iter(global_modes)) if len(global_modes) == 1 else None
	for col in range(1, outliers_ws.max_column + 1):
		head_value = outliers_ws.cell(1, col).value
		header_text = normalize_temp_name(head_value)
		q_value = _try_parse_float(head_value)
		if q_value is not None and abs(q_value - 0.01) > 1e-12:
			continue
		mode = column_modes.get(col)
		if mode is None and q_value is not None and "0.01" not in header_text:
			continue
		mode = mode or default_mode
		if mode is None:
			continue
		for row in range(2, outliers_ws.max_row + 1):
			sample_value = normalize_temp_name(outliers_ws.cell(row, col).value)
			if sample_value:
				lookup = log10_lookup if mode == "log10" else linear_lookup
				lookup[canonical_lookup_key(sample_value)] = 0.01
	return linear_lookup, log10_lookup


def populate_outlier_column(all_res_ws, all_res_cols: Dict[str, int], outliers_ws) -> None:
	if "temp.name" not in all_res_cols or "outlier" not in all_res_cols or "outlier_log10" not in all_res_cols:
		raise ValueError("all.res sheet is missing Temp.name, Outlier, or Outlier_log10 columns")
	if "type" not in all_res_cols:
		raise ValueError("all.res sheet is missing Type column")

	linear_lookup, log10_lookup = build_outlier_lookups(outliers_ws)
	first_valid_rows: Dict[str, Tuple[Tuple[int, str], int]] = {}
	for row in range(2, all_res_ws.max_row + 1):
		type_value = str(all_res_ws.cell(row, all_res_cols["type"]).value or "").strip().lower()
		outlier_cell = all_res_ws.cell(row, all_res_cols["outlier"])
		outlier_cell.value = None
		all_res_ws.cell(row, all_res_cols["outlier_log10"]).value = None
		if type_value != "s":
			continue
		sample_name = normalize_temp_name(all_res_ws.cell(row, all_res_cols["sample"]).value)
		if not sample_name:
			continue
		key = canonical_lookup_key(sample_name)
		if key not in linear_lookup and key not in log10_lookup:
			continue
		plate_key = _plate_sort_key(all_res_ws.cell(row, all_res_cols["plate"]).value)
		previous = first_valid_rows.get(key)
		if previous is None or plate_key < previous[0]:
			first_valid_rows[key] = (plate_key, row)

	for sample_key, (_, row) in first_valid_rows.items():
		if sample_key in linear_lookup:
			outlier_cell = all_res_ws.cell(row, all_res_cols["outlier"])
			outlier_cell.value = linear_lookup[sample_key]
			set_three_decimal(outlier_cell)
		if sample_key in log10_lookup:
			outlier_log10_cell = all_res_ws.cell(row, all_res_cols["outlier_log10"])
			outlier_log10_cell.value = log10_lookup[sample_key]
			set_three_decimal(outlier_log10_cell)


def populate_all_res_metadata(all_res_ws, all_res_cols: Dict[str, int]) -> None:
	for row in range(2, all_res_ws.max_row + 1):
		plate = normalize_temp_name(all_res_ws.cell(row, all_res_cols["plate"]).value)
		sample = normalize_temp_name(all_res_ws.cell(row, all_res_cols["sample"]).value)
		comments = all_res_ws.cell(row, all_res_cols["comments"]).value
		if not plate or not sample:
			continue
		all_res_ws.cell(row, all_res_cols["temp.name"], f"{plate}.{sample}")
		all_res_ws.cell(row, all_res_cols["type"], all_res_type_label(plate, sample, comments))


def _plate_sort_key(value: object) -> Tuple[int, str]:
	text = normalize_temp_name(value)
	match = re.search(r"PL(\d+)", text, flags=re.IGNORECASE)
	if match:
		return int(match.group(1)), text
	return (10**9, text)


def populate_all_res_cutoff(all_res_ws, cutoff_ws) -> None:
	all_res_cols = header_column_map(all_res_ws)
	cutoff_cols = header_column_map(cutoff_ws)
	if "type" not in all_res_cols or "cutoff" not in all_res_cols or "co_p99.5" not in cutoff_cols:
		return
	cutoff_value = next(
		(
			_try_parse_float(cutoff_ws.cell(row, cutoff_cols["co_p99.5"]).value)
			for row in range(2, cutoff_ws.max_row + 1)
			if _try_parse_float(cutoff_ws.cell(row, cutoff_cols["co_p99.5"]).value) is not None
		),
		None,
	)
	for row in range(2, all_res_ws.max_row + 1):
		type_value = normalize_temp_name(all_res_ws.cell(row, all_res_cols["type"]).value).lower()
		cutoff_cell = all_res_ws.cell(row, all_res_cols["cutoff"])
		cutoff_cell.value = cutoff_value if type_value == "s" else None
		if cutoff_value is not None and type_value == "s":
			set_three_decimal(cutoff_cell)


def build_cutoff_sheet(
	wb,
	all_res_ws,
	all_res_cols: Dict[str, int],
	outlier_lookups: Optional[Tuple[Dict[str, float], Dict[str, float]]] = None,
) -> None:
	if "cutoff" in wb.sheetnames:
		del wb["cutoff"]
	cutoff_ws = wb.create_sheet("cutoff")
	headers = ("Sample", "Cond", "Outlier")
	for idx in range(1, 5):
		headers += (f"Mean_SP{idx}",)
	for idx in range(1, 5):
		headers += (f"Mean_ODn{idx}",)
	for col, header in enumerate(headers, start=1):
		cutoff_ws.cell(1, col, header)

	linear_outlier_lookup, _ = outlier_lookups or ({}, {})
	groups: Dict[str, List[Dict[str, object]]] = {}
	for row in range(2, all_res_ws.max_row + 1):
		type_value = normalize_temp_name(all_res_ws.cell(row, all_res_cols["type"]).value).lower()
		if type_value != "s":
			continue
		sample = normalize_temp_name(all_res_ws.cell(row, all_res_cols["sample"]).value)
		if not sample:
			continue
		comments = all_res_ws.cell(row, all_res_cols["comments"]).value
		condition_tags = extract_conditions(comments)
		odn_values = [
			value
			for value in (
				_try_parse_float(all_res_ws.cell(row, all_res_cols[f"res{idx}"]).value)
				for idx in range(1, 5)
			)
			if value is not None
		]
		qc_values, _ = apply_sample_qc(type_value, odn_values)
		mean_odn = statistics.mean(qc_values) if qc_values else None
		mean_sp = _try_parse_float(all_res_ws.cell(row, all_res_cols["mean_sp"]).value)
		groups.setdefault(sample, []).append(
			{
				"plate": all_res_ws.cell(row, all_res_cols["plate"]).value,
				"conditions": condition_tags,
				"mean_sp": mean_sp,
				"mean_odn": mean_odn,
			}
		)

	row_out = 2
	for sample, records in sorted(groups.items(), key=lambda item: item[0]):
		records.sort(key=lambda record: _plate_sort_key(record["plate"]))
		condition_tags = set()
		for record in records:
			condition_tags.update(record["conditions"])
		cutoff_ws.cell(row_out, 1, sample)
		cutoff_ws.cell(row_out, 2, format_condition_tags(condition_tags))
		cutoff_ws.cell(row_out, 3, linear_outlier_lookup.get(canonical_lookup_key(sample)))
		for idx, record in enumerate(records[:4], start=1):
			sp_cell = cutoff_ws.cell(row_out, 3 + idx, record["mean_sp"])
			odn_cell = cutoff_ws.cell(row_out, 7 + idx, record["mean_odn"])
			if record["mean_sp"] is not None:
				set_three_decimal(sp_cell)
			if record["mean_odn"] is not None:
				set_three_decimal(odn_cell)
		row_out += 1


def _fit_gaussian_mixture(values: Sequence[float], components: int) -> Optional[Dict[str, object]]:
	import numpy as np

	x = np.asarray(list(values), dtype=float)
	if x.size < components or not np.all(np.isfinite(x)):
		return None
	variance_floor = max(float(np.var(x)) * 1e-6, 1e-8)
	if components == 1:
		variance = max(float(np.var(x)), variance_floor)
		return {
			"weights": np.array([1.0]),
			"means": np.array([float(np.mean(x))]),
			"variances": np.array([variance]),
			"log_likelihood": float(np.sum(-0.5 * (np.log(2 * np.pi * variance) + (x - np.mean(x)) ** 2 / variance))),
		}

	if float(np.ptp(x)) <= 0:
		return None
	means = np.array([float(np.quantile(x, 0.3)), float(np.quantile(x, 0.7))])
	weights = np.array([0.5, 0.5])
	variances = np.array([max(float(np.var(x)), variance_floor)] * components)
	previous_ll = -float("inf")
	for _ in range(300):
		log_density = np.empty((x.size, components))
		for idx in range(components):
			log_density[:, idx] = (
				math.log(weights[idx])
				- 0.5 * math.log(2 * math.pi * variances[idx])
				- 0.5 * (x - means[idx]) ** 2 / variances[idx]
			)
		max_log = np.max(log_density, axis=1)
		log_total = max_log + np.log(np.sum(np.exp(log_density - max_log[:, None]), axis=1))
		responsibilities = np.exp(log_density - log_total[:, None])
		counts = np.sum(responsibilities, axis=0)
		weights = counts / x.size
		means = np.sum(responsibilities * x[:, None], axis=0) / counts
		variances = np.sum(responsibilities * (x[:, None] - means) ** 2, axis=0) / counts
		variances = np.maximum(variances, variance_floor)
		log_likelihood = float(np.sum(log_total))
		if abs(log_likelihood - previous_ll) < 1e-8:
			break
		previous_ll = log_likelihood

	order = np.argsort(means)
	return {
		"weights": weights[order],
		"means": means[order],
		"variances": variances[order],
		"log_likelihood": log_likelihood,
	}


def _mixture_bic(model: Dict[str, object], sample_count: int, components: int) -> float:
	parameter_count = 3 * components - 1
	return -2 * float(model["log_likelihood"]) + parameter_count * math.log(sample_count)


def _mixture_density(model: Dict[str, object], values):
	import numpy as np

	density = np.zeros_like(values, dtype=float)
	for weight, mean, variance in zip(model["weights"], model["means"], model["variances"]):
		density += weight * np.exp(-0.5 * (values - mean) ** 2 / variance) / math.sqrt(2 * math.pi * variance)
	return density


def _mixture_intersections(model: Dict[str, object]) -> List[float]:
	import numpy as np

	means = model["means"]
	variances = model["variances"]
	weights = model["weights"]
	if len(means) != 2 or means[0] >= means[1]:
		return []
	# Solve log(w1*N1) = log(w2*N2). Unequal variances can produce two real roots;
	# retain every numerically real root and select the between-means root separately.
	a = 1.0 / variances[1] - 1.0 / variances[0]
	b = -2 * means[1] / variances[1] + 2 * means[0] / variances[0]
	c = (means[1] ** 2 / variances[1] - means[0] ** 2 / variances[0]
		 + math.log(variances[1] / variances[0])
		 - 2 * math.log(weights[1] / weights[0]))
	if abs(a) < 1e-12:
		roots = [-c / b] if abs(b) > 1e-12 else []
	else:
		roots = np.roots([a, b, c])
	return sorted({round(float(root.real), 12) for root in roots if abs(float(root.imag)) < 1e-8 and math.isfinite(float(root.real))})


def _mixture_intersection(model: Dict[str, object]) -> Optional[float]:
	means = model["means"]
	roots = _mixture_intersections(model)
	between = [root for root in roots if means[0] <= root <= means[1]]
	return between[0] if between else None


def _bootstrap_intersections(values: Sequence[float], bootstrap_count: int = 500) -> List[float]:
	import numpy as np

	rng = np.random.default_rng(20260910)
	values_array = np.asarray(list(values), dtype=float)
	intersections: List[float] = []
	for _ in range(bootstrap_count):
		sample = rng.choice(values_array, size=values_array.size, replace=True)
		model = _fit_gaussian_mixture(sample, 2)
		if model is None:
			continue
		intersection = _mixture_intersection(model)
		if intersection is not None and math.isfinite(intersection):
			intersections.append(intersection)
	return intersections


