def duplicate_well_pairs() -> List[Tuple[str, str]]:
	pairs: List[Tuple[str, str]] = []
	for start_col in range(1, 13, 2):
		for row_letter in "ABCDEFGH":
			pairs.append(
				(f"{row_letter}{start_col}", f"{row_letter}{start_col + 1}")
			)
	return pairs


def short_plate_name(name: str) -> str:
	match = re.search(r"(PL\d+)", name, flags=re.IGNORECASE)
	if not match:
		raise ValueError(f"Could not find shorthand plate name (PLx) in: {name!r}")
	return match.group(1).upper()


def extract_date_token(*candidates: str) -> Optional[str]:
	for text in candidates:
		match = re.search(r"\d{2}\.\d{2}\.\d{2}", text)
		if match:
			return match.group(0)
	return None


def format_date_uk(date_token: str) -> str:
	parsed = datetime.strptime(date_token, "%y.%m.%d")
	return parsed.strftime("%d/%m/%Y")


def _try_parse_float(value: object) -> Optional[float]:
	if value is None:
		return None
	text = str(value).strip()
	if not text:
		return None
	try:
		return float(text)
	except ValueError:
		return None


def _read_tab_export_rows(input_path: Path) -> List[List[str]]:
	text = input_path.read_text(encoding="utf-16")
	rows: List[List[str]] = []
	for row in csv.reader(text.splitlines(), delimiter="\t"):
		rows.append([cell.strip() for cell in row])
	return rows


def _cell_float(row: Sequence[str], index_zero_based: int) -> Optional[float]:
	if index_zero_based < 0 or index_zero_based >= len(row):
		return None
	return _try_parse_float(row[index_zero_based])


def _wavelength_order(plate_header_row: Sequence[str]) -> Tuple[int, int]:
	joined = " ".join(cell for cell in plate_header_row if cell)
	wavelengths = [int(w) for w in re.findall(r"\b(450|620)\b", joined)]
	if len(wavelengths) < 2:
		raise ValueError(
			"Could not identify 450 and 620 wavelength order in plate header row."
		)
	left, right = wavelengths[0], wavelengths[1]
	if {left, right} != {450, 620}:
		raise ValueError(f"Unexpected wavelength pair found: {left}, {right}")
	return left, right


def parse_elisa_export(input_path: Path) -> List[PlateResult]:
	rows = _read_tab_export_rows(input_path)
	parsed: List[PlateResult] = []

	i = 0
	while i < len(rows):
		row = rows[i]
		first_cell = row[0] if row else ""
		if not first_cell.startswith("Plate"):
			i += 1
			continue

		if len(row) < 2 or not row[1]:
			raise ValueError(f"Plate row is missing plate name around row {i + 1}.")

		plate_full = row[1]
		plate_short = short_plate_name(plate_full)
		left_wl, right_wl = _wavelength_order(row)

		corrected: Dict[str, float] = {}
		# Plate matrix layout from instrument export:
		# - row A starts 2 rows below "Plate:" line
		# - left measurement starts at column 3
		# - paired wavelength starts 13 columns to the right (column 16)
		data_row_start = i + 2
		left_col_start = 2
		right_col_start = left_col_start + 13

		for row_idx in range(8):
			source_row_idx = data_row_start + row_idx
			if source_row_idx >= len(rows):
				row_letter = "ABCDEFGH"[row_idx]
				raise ValueError(
					f"Plate {plate_short}: expected row for {row_letter}, but file ended early."
				)

			source_row = rows[source_row_idx]
			row_letter = "ABCDEFGH"[row_idx]
			for col_idx in range(1, 13):
				left_value = _cell_float(source_row, left_col_start + (col_idx - 1))
				right_value = _cell_float(source_row, right_col_start + (col_idx - 1))

				if left_wl == 450:
					val_450, val_620 = left_value, right_value
				else:
					val_450, val_620 = right_value, left_value

				well = f"{row_letter}{col_idx}"
				if val_450 is None or val_620 is None:
					continue
				corrected[well] = val_450 - val_620

		if len(corrected) < 96:
			raise ValueError(
				f"Plate {plate_short}: expected 96 corrected well values, found {len(corrected)}."
			)

		j = i + 1
		while j < len(rows):
			r = rows[j]
			marker = r[0] if r else ""
			if marker.startswith("Plate"):
				break
			j += 1

		parsed.append(
			PlateResult(
				plate_full_name=plate_full,
				plate_short_name=plate_short,
				corrected_by_well=corrected,
			)
		)

		if j < len(rows) and rows[j] and rows[j][0].startswith("Plate"):
			i = j
		else:
			i = j + 1

	if not parsed:
		raise ValueError(
			"No plate blocks found in file. Expected 'Plate:' rows like the example export."
		)
	return parsed


def load_platemap_layout(output_workbook: Path) -> Dict[str, List[PlatemapEntry]]:
	wb = load_workbook(output_workbook, read_only=True, data_only=False)
	if PLATEMAP_SHEET not in wb.sheetnames:
		raise ValueError(f"Workbook missing required sheet: {PLATEMAP_SHEET}")

	ws = wb[PLATEMAP_SHEET]
	plate_columns: Dict[str, int] = {}
	for col in range(1, ws.max_column + 1):
		value = ws.cell(1, col).value
		if isinstance(value, str) and re.fullmatch(r"PL\d+", value.strip(), re.IGNORECASE):
			plate_columns[value.strip().upper()] = col

	if not plate_columns:
		raise ValueError("No PLx plate columns found in 'platemaps' header row.")

	pairs = duplicate_well_pairs()
	plate_layout: Dict[str, List[PlatemapEntry]] = {}

	for plate_name, sample_col in plate_columns.items():
		box_col = sample_col - 1
		comment_col = sample_col + 1
		entries: List[PlatemapEntry] = []

		for idx, excel_row in enumerate(range(2, ws.max_row + 1)):
			if idx >= len(pairs):
				break
			sample_val = ws.cell(excel_row, sample_col).value
			if sample_val is None or str(sample_val).strip() == "":
				continue
			entries.append(
				PlatemapEntry(
					box=ws.cell(excel_row, box_col).value,
					sample=str(sample_val).strip(),
					comments=ws.cell(excel_row, comment_col).value,
					well_a=pairs[idx][0],
					well_b=pairs[idx][1],
				)
			)

		plate_layout[plate_name] = entries

	wb.close()
	return plate_layout


def copy_input_sheet(source_ws, target_wb) -> None:
	if source_ws.title in target_wb.sheetnames:
		del target_wb[source_ws.title]
	target_ws = target_wb.create_sheet(source_ws.title)
	for row in source_ws.iter_rows():
		for source_cell in row:
			target_cell = target_ws.cell(source_cell.row, source_cell.column, source_cell.value)
			if source_cell.has_style:
				target_cell._style = copy.copy(source_cell._style)
			if source_cell.number_format:
				target_cell.number_format = source_cell.number_format
			if source_cell.alignment:
				target_cell.alignment = copy.copy(source_cell.alignment)
			if source_cell.protection:
				target_cell.protection = copy.copy(source_cell.protection)
	for merged_range in source_ws.merged_cells.ranges:
		target_ws.merge_cells(str(merged_range))
	for column_letter, dimension in source_ws.column_dimensions.items():
		target_ws.column_dimensions[column_letter] = copy.copy(dimension)
	for row_number, dimension in source_ws.row_dimensions.items():
		target_ws.row_dimensions[row_number] = copy.copy(dimension)
	target_ws.freeze_panes = source_ws.freeze_panes


