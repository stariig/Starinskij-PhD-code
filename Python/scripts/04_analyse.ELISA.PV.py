def process_pvnt_file(input_path: Path, wb_out) -> None:
	"""Process a pVNT .xlsx file and write ReadDate and Res into PV.maps sheet.

	File name expected to contain date token YY.MM.DD and plate name like PV1 or PV12.
	Data lives in sheet 'Results' in range F11:Q18 (A-H x 1-12 layout).
	"""
	fname = input_path.name
	date_token = extract_date_token(fname)
	if not date_token:
		raise ValueError(f"Could not detect date token in pVNT file name: {fname}")
	file_date_uk = format_date_uk(date_token)

	plate_match = re.search(r"\b(PV\d{1,2})\b", fname, flags=re.IGNORECASE)
	if not plate_match:
		raise ValueError(f"Could not detect plate name (PV#) in pVNT file name: {fname}")
	plate_name = plate_match.group(1).upper()

	wb_in = load_workbook(input_path, data_only=True)
	if "Results" in wb_in.sheetnames:
		res_ws = wb_in["Results"]
	elif len(wb_in.worksheets) >= 2:
		res_ws = wb_in.worksheets[1]
	else:
		raise ValueError(f"pVNT workbook {fname} missing Results sheet")

	# Read F11:Q18 -> columns 6..17, rows 11..18
	pv_values: Dict[str, object] = {}
	row_letters = "ABCDEFGH"
	for r_idx, row in enumerate(range(11, 19)):
		row_letter = row_letters[r_idx]
		for c_idx, col in enumerate(range(6, 18)):
			well = f"{row_letter}{c_idx+1}"
			cell_val = res_ws.cell(row=row, column=col).value
			norm_well = normalize_well(well)
			if norm_well:
				pv_values[norm_well] = cell_val

	# Locate PV.maps in the input workbook; only ReadDate and Res are written.
	if "PV.maps" not in wb_out.sheetnames:
		raise ValueError("Output workbook missing required sheet: PV.maps")
	pv_ws = wb_out["PV.maps"]

	headers = header_column_map(pv_ws)
	# Columns to edit
	readdate_col = headers.get("readdate") or headers.get("read date") or headers.get("read_date")
	res_col = headers.get("res")
	# Try find well column header alternatives
	well_col = (
		headers.get("well")
		or headers.get("pos")
		or headers.get("position")
		or headers.get("wellid")
		or headers.get("well id")
	)
	# Fallback: assume Plate in column A and Well in a headered column
	if readdate_col is None or res_col is None:
		raise ValueError("PV.maps sheet must contain headers 'ReadDate' and 'Res'")
	if well_col is None:
		raise ValueError("PV.maps sheet must contain a header for well (well/pos/position)")

	# Iterate rows and update those matching plate_name
	plate_col_index = 1
	for row in range(2, pv_ws.max_row + 1):
		plate_cell = pv_ws.cell(row, plate_col_index).value
		if not plate_cell:
			continue
		if str(plate_cell).strip().upper() != plate_name:
			continue

		well_cell = pv_ws.cell(row, well_col).value
		norm_well = normalize_well(well_cell)
		if not norm_well:
			continue
		if norm_well in pv_values:
			pv_ws.cell(row, readdate_col).value = file_date_uk
			pv_ws.cell(row, res_col).value = pv_values[norm_well]
	wb_in.close()


def copy_pv_results_to_results_workbook(input_wb, results_wb) -> None:
	"""Mirror only PV.maps ReadDate and Res values into the results workbook."""
	if "PV.maps" not in input_wb.sheetnames or "PV.maps" not in results_wb.sheetnames:
		return
	input_ws = input_wb["PV.maps"]
	results_ws = results_wb["PV.maps"]
	input_cols = header_column_map(input_ws)
	results_cols = header_column_map(results_ws)
	for header in ("readdate", "res"):
		if header not in input_cols or header not in results_cols:
			raise ValueError(f"PV.maps sheet must contain header {header!r}")
	for row in range(1, input_ws.max_row + 1):
		results_ws.cell(row, results_cols["readdate"], input_ws.cell(row, input_cols["readdate"]).value)
		results_ws.cell(row, results_cols["res"], input_ws.cell(row, input_cols["res"]).value)


def source_column_map(source_ws) -> Dict[str, int]:
	cols = header_column_map(source_ws)

	def first_existing(names: Sequence[str]) -> Optional[int]:
		for name in names:
			if name in cols:
				return cols[name]
		return None

	box_col = first_existing(("box", "new box", "box no", "box number"))
	sample_col = first_existing(("sample", "sample name", "deerid", "deer id", "name"))
	position_col = first_existing(("position", "pos", "new pos", "new position"))

	# Fallback to user-specified order if one or more headers are unavailable.
	if box_col is None:
		box_col = 1
	if sample_col is None:
		sample_col = 2
	if position_col is None:
		position_col = 3

	return {"box": box_col, "sample": sample_col, "position": position_col}


def build_source_lookup(source_ws, source_cols: Dict[str, int]) -> Dict[str, Tuple[object, object]]:
	source_lookup: Dict[str, Tuple[object, object]] = {}
	for row in range(2, source_ws.max_row + 1):
		sample = normalize_temp_name(source_ws.cell(row, source_cols["sample"]).value)
		if not sample:
			continue
		if sample not in source_lookup:
			box = source_ws.cell(row, source_cols["box"]).value
			pos = source_ws.cell(row, source_cols["position"]).value
			source_lookup[sample] = (box, pos)
	return source_lookup


def write_summary_sheet(ws, source_position_lookup, sample_records, sample_conditions, included_samples, sample_box_map, source_boxes_by_sample, cutoff, negative_sheet: bool = False) -> None:
	max_runs = 0
	for sample_name in included_samples:
		max_runs = max(max_runs, len(sample_records[sample_name]))

	initialize_summary_sheet(ws)
	for idx in range(1, max_runs + 1):
		base_col = 5 + (idx - 1) * 4
		ws.cell(1, base_col, f"PL{idx}")
		ws.cell(1, base_col + 1, f"Mean_SP{idx}")
		ws.cell(1, base_col + 2, f"Mean_ODn{idx}")
		ws.cell(1, base_col + 3, f"Above_CO_P99.5{idx}")

	# Add Call header after all run columns
	call_col = 5 + max_runs * 4
	ws.cell(1, call_col, "Call")

	row_out = 2
	for sample_name in included_samples:
		# Determine which box to use for lookup
		num_boxes = len(source_boxes_by_sample.get(sample_name, set()))
		if num_boxes > 1:
			# Multiple boxes in source: use the box from all.res (the tested box)
			box_to_use = sample_box_map.get(sample_name, "")
		else:
			# Single box or not found: use the one box available
			available_boxes = source_boxes_by_sample.get(sample_name, set())
			box_to_use = list(available_boxes)[0] if available_boxes else ""

		# Look up (box, sample) in source
		lookup_key = (box_to_use, sample_name)
		box_value, pos_value = None, None
		if lookup_key in source_position_lookup:
			entries = source_position_lookup[lookup_key]
			if entries:
				box_value = entries[0][0]
				for candidate_box, candidate_pos in entries:
					if box_value in (None, "") and candidate_box not in (None, ""):
						box_value = candidate_box
					if candidate_pos not in (None, "", "missing"):
						pos_value = candidate_pos
						break

		ws.cell(row_out, 1, box_value)
		ws.cell(row_out, 2, sample_name)
		ws.cell(row_out, 3, pos_value)
		ws.cell(row_out, 4, format_condition_tags(sample_conditions.get(sample_name, set())))
		positive_count = 0
		for idx, record in enumerate(sample_records[sample_name], start=1):
			base_col = 5 + (idx - 1) * 4
			mean_sp = record["mean_sp"]
			mean_odn = record["mean_odn"]
			above_cutoff = None if mean_sp is None or cutoff is None else mean_sp - cutoff
			ws.cell(row_out, base_col, record["plate"])
			ws.cell(row_out, base_col + 1, mean_sp)
			ws.cell(row_out, base_col + 2, mean_odn)
			ws.cell(row_out, base_col + 3, above_cutoff)
			if mean_sp is not None:
				set_three_decimal(ws.cell(row_out, base_col + 1))
			if mean_odn is not None:
				set_three_decimal(ws.cell(row_out, base_col + 2))
			if above_cutoff is not None:
				set_three_decimal(ws.cell(row_out, base_col + 3))
			if mean_sp is not None and cutoff is not None and mean_sp > cutoff:
				positive_count += 1
		call_value = "neg" if negative_sheet else ("pos" if positive_count >= 2 else ("eq" if positive_count == 1 else "neg"))
		ws.cell(row_out, call_col, call_value)
		
		row_out += 1


def rebuild_positives_and_negatives_sheets(wb, all_res_ws, all_res_cols: Dict[str, int]) -> None:
	if "positives" not in wb.sheetnames:
		wb.create_sheet("positives")
	if "negatives" not in wb.sheetnames:
		wb.create_sheet("negatives")
	if "source" not in wb.sheetnames:
		raise ValueError("Workbook missing required sheet: source")

	positives_ws = wb["positives"]
	negatives_ws = wb["negatives"]
	source_ws = wb["source"]
	source_cols = source_column_map(source_ws)

	# Build lookup: (box_key, sample) -> list of (box_value, position)
	source_position_lookup: Dict[Tuple[str, str], List[Tuple[object, object]]] = {}
	source_boxes_by_sample: Dict[str, set[str]] = {}
	for row in range(2, source_ws.max_row + 1):
		sample = normalize_temp_name(source_ws.cell(row, source_cols["sample"]).value)
		box = source_ws.cell(row, source_cols["box"]).value
		pos = source_ws.cell(row, source_cols["position"]).value
		if sample:
			box_key = normalize_key_part(box) if box else ""
			source_position_lookup.setdefault((box_key, sample), []).append((box, pos))
			source_boxes_by_sample.setdefault(sample, set()).add(box_key)

	sample_records: Dict[str, List[Dict[str, object]]] = {}
	sample_conditions: Dict[str, set[str]] = {}
	sample_box_map: Dict[str, str] = {}
	positive_sample_names: set[str] = set()
	cutoff = None
	if "cutoff" in wb.sheetnames:
		cutoff_ws = wb["cutoff"]
		cutoff_cols = header_column_map(cutoff_ws)
		if "co_p99.5" in cutoff_cols:
			cutoff = next(
				(_try_parse_float(cutoff_ws.cell(row, cutoff_cols["co_p99.5"]).value)
				 for row in range(2, cutoff_ws.max_row + 1)
				 if _try_parse_float(cutoff_ws.cell(row, cutoff_cols["co_p99.5"]).value) is not None),
				None,
			)

	for row in range(2, all_res_ws.max_row + 1):
		type_value = str(all_res_ws.cell(row, all_res_cols["type"]).value or "").strip().lower()
		if type_value != "s":
			continue
		sample_name = normalize_temp_name(all_res_ws.cell(row, all_res_cols["sample"]).value)
		if not sample_name:
			continue

		box_from_data = normalize_key_part(all_res_ws.cell(row, all_res_cols["box"]).value)
		sample_box_map[sample_name] = box_from_data

		run_value = all_res_ws.cell(row, all_res_cols["plate"]).value
		res_value = _try_parse_float(all_res_ws.cell(row, all_res_cols["mean_sp"]).value)
		odn_values = [_try_parse_float(all_res_ws.cell(row, all_res_cols[f"res{idx}"]).value) for idx in range(1, 5)]
		odn_values = [value for value in odn_values if value is not None]
		mean_odn = statistics.mean(odn_values) if odn_values else None
		sample_records.setdefault(sample_name, []).append({"plate": run_value, "mean_sp": res_value, "mean_odn": mean_odn})
		sample_conditions.setdefault(sample_name, set()).update(extract_conditions(all_res_ws.cell(row, all_res_cols["comments"]).value))
		# A sample is positive when any run reaches the clean-result cutoff.
		if cutoff is not None and res_value is not None and res_value > cutoff:
			positive_sample_names.add(sample_name)

	included_samples = [name for name in sample_records.keys() if name in positive_sample_names]
	negative_samples = [name for name in sample_records.keys() if name not in positive_sample_names]

	write_summary_sheet(positives_ws, source_position_lookup, sample_records, sample_conditions, included_samples, sample_box_map, source_boxes_by_sample, cutoff)
	# Reapply thick border layout to positives sheet after writing
	rebuild_summary_sheet_borders(positives_ws)
	write_summary_sheet(negatives_ws, source_position_lookup, sample_records, sample_conditions, negative_samples, sample_box_map, source_boxes_by_sample, cutoff, negative_sheet=True)
	call_col = header_column_map(negatives_ws).get("call")
	if call_col is not None:
		for row in range(2, negatives_ws.max_row + 1):
			if normalize_temp_name(negatives_ws.cell(row, 2).value):
				negatives_ws.cell(row, call_col, "neg")
	# Reapply thick border layout to negatives sheet after writing
	rebuild_summary_sheet_borders(negatives_ws)


def populate_source_conditions(source_ws, source_cols: Dict[str, int], all_res_ws, all_res_cols: Dict[str, int]) -> None:
	source_header_cols = header_column_map(source_ws)
	condition_col = (
		source_header_cols.get("condition")
		or source_header_cols.get("cond")
		or source_header_cols.get("conditions")
	)
	if condition_col is None:
		return

	conditions_by_key: Dict[Tuple[str, str], set[str]] = {}
	for row in range(2, all_res_ws.max_row + 1):
		sample = normalize_temp_name(all_res_ws.cell(row, all_res_cols["sample"]).value)
		if not sample:
			continue
		box = normalize_key_part(all_res_ws.cell(row, all_res_cols["box"]).value)
		if not box:
			continue
		tags = extract_conditions(all_res_ws.cell(row, all_res_cols["comments"]).value)
		if not tags:
			continue
		key = (box, sample)
		conditions_by_key.setdefault(key, set()).update(tags)

	for row in range(2, source_ws.max_row + 1):
		sample = normalize_temp_name(source_ws.cell(row, source_cols["sample"]).value)
		box = normalize_key_part(source_ws.cell(row, source_cols["box"]).value)
		cell = source_ws.cell(row, condition_col)
		if not sample or not box:
			cell.value = None
			continue
		cell.value = format_condition_tags(conditions_by_key.get((box, sample), set()))


def normalize_outliers_sheet(outliers_ws) -> None:
	for row in range(1, outliers_ws.max_row + 1):
		for col in range(1, outliers_ws.max_column + 1):
			cell = outliers_ws.cell(row, col)
			if isinstance(cell.value, str) and "\xa0" in cell.value:
				cell.value = cell.value.replace("\xa0", " ")


def mean_and_sd(values: Sequence[float]) -> Tuple[Optional[float], Optional[float]]:
	if not values:
		return None, None
	if len(values) == 1:
		return values[0], 0.0
	# Use sample SD (n-1), equivalent to Excel STDEV.S.
	# This is the common choice when estimating plate-to-plate variability from sampled wells.
	return statistics.mean(values), statistics.stdev(values)


def apply_sample_qc(
	type_value: str,
	odn_values: Sequence[float],
) -> Tuple[List[float], List[int]]:
	qc_values = list(odn_values)
	removed_indices: List[int] = []
	if type_value != "s" or len(qc_values) < 2:
		return qc_values, removed_indices

	# For s-type samples, drop a single high replicate when the pair is clearly discordant
	# and at least one measurement is already above the low-signal threshold.
	if not any(value > 0.1 for value in qc_values):
		return qc_values, removed_indices

	low_value = min(qc_values)
	high_value = max(qc_values)
	if low_value <= 0:
		return qc_values, removed_indices
	if high_value <= low_value * 2:
		return qc_values, removed_indices

	removed_index = qc_values.index(high_value)
	qc_values.pop(removed_index)
	removed_indices.append(removed_index)
	return qc_values, removed_indices


def is_control(sample_name: str, control_label: str) -> bool:
	return control_label.lower() in sample_name.lower()


def parse_dilution_denominator(sample_name: str) -> Optional[int]:
	match = re.search(r"1\s*:\s*(\d+)", sample_name)
	if not match:
		return None
	return int(match.group(1))


def control_bucket(sample_name: str) -> Optional[str]:
	sample = sample_name.strip()
	sample_lower = sample.lower()
	if is_control(sample, "neg"):
		return "neg"
	if is_control(sample, "low"):
		return "low"
	if is_control(sample, "nsc"):
		return "nsc"
	if "high" in sample_lower:
		dilution = parse_dilution_denominator(sample)
		if dilution is not None and dilution > 200:
			return "highdil"
		return "high"
	return None


def process_files(
	input_files: Sequence[Path],
	input_workbook: Path,
	output_workbook: Path,
	metadata_workbook: Path = DEFAULT_METADATA_XLSX,
	processing_steps: Optional[Dict[str, bool]] = None,
) -> None:
	processing_steps = processing_steps or {}
	has_elisa_inputs = any(input_file.suffix.lower() == ".xls" for input_file in input_files)
	elisa_inputs = [input_file for input_file in input_files if input_file.suffix.lower() == ".xls"]
	pv_inputs = [input_file for input_file in input_files if input_file.suffix.lower() == ".xlsx"]
	needs_input_workbook = (
		has_elisa_inputs
		or pv_inputs
		or processing_steps.get("move_elisa", False)
		or processing_steps.get("graphs", False)
		or processing_steps.get("random_graph", False)
	)
	if needs_input_workbook and not input_workbook.exists():
		raise FileNotFoundError(f"Input workbook does not exist: {input_workbook}")
	input_wb = None
	platemap_layout: Dict[str, List[PlatemapEntry]] = {}
	if has_elisa_inputs:
		platemap_layout = load_platemap_layout(input_workbook)
		input_wb = load_workbook(input_workbook, data_only=False)
		wb = create_results_workbook(input_workbook)
	elif output_workbook.exists():
		# A PV-only run must preserve the existing ELISA result sheets.
		wb = load_workbook(output_workbook, data_only=False)
		if pv_inputs or processing_steps.get("move_elisa", False) or processing_steps.get("graphs", False) or processing_steps.get("random_graph", False):
			input_wb = load_workbook(input_workbook, data_only=False)
			sheets_to_copy = ["source"] if processing_steps.get("move_elisa", False) or processing_steps.get("graphs", False) or processing_steps.get("random_graph", False) else []
			if pv_inputs or processing_steps.get("graphs", False) or processing_steps.get("random_graph", False):
				sheets_to_copy.append("PV.maps")
			for sheet_name in sheets_to_copy:
				copy_input_sheet(input_wb[sheet_name], wb)
	else:
		raise FileNotFoundError(f"Output workbook does not exist: {output_workbook}")

	if RAW_SHEET not in wb.sheetnames:
		raise ValueError(f"Workbook missing required sheet: {RAW_SHEET}")
	if CTRL_SHEET not in wb.sheetnames:
		raise ValueError(f"Workbook missing required sheet: {CTRL_SHEET}")
	if ALL_RES_SHEET not in wb.sheetnames:
		raise ValueError(f"Workbook missing required sheet: {ALL_RES_SHEET}")
	if processing_steps.get("all_res", False) and "outliers" not in wb.sheetnames:
		raise ValueError("Workbook missing required sheet: outliers")

	raw_ws = wb[RAW_SHEET]
	ctrl_ws = wb[CTRL_SHEET]
	all_res_ws = wb[ALL_RES_SHEET]
	outliers_ws = wb["outliers"] if "outliers" in wb.sheetnames else None
	legacy_co_columns = [
		col for col in range(1, all_res_ws.max_column + 1)
		if normalize_temp_name(all_res_ws.cell(1, col).value).lower() == "co"
	]
	for col in reversed(legacy_co_columns):
		all_res_ws.delete_cols(col)
	if outliers_ws is not None:
		normalize_outliers_sheet(outliers_ws)

	raw_cols = header_column_map(raw_ws)
	required_raw_headers = ["date", "pos", "plate", "box", "sample", "comments", "od", "odn"]
	missing_raw_headers = [h for h in required_raw_headers if h not in raw_cols]
	if missing_raw_headers:
		raise ValueError(
			f"Raw sheet is missing expected headers: {', '.join(missing_raw_headers)}"
		)

	ctrl_cols = header_column_map(ctrl_ws)
	required_ctrl_headers = [
		"date",
		"plate",
		"mean.neg.od",
		"sd.neg.od",
		"mean.high.od",
		"sd.high.od",
		"mean.highdil.od",
		"sd.highdil.od",
		"mean.low.od",
		"sd.low.od",
		"mean.nsc.od",
		"sd.nsc.od",
		"5sd.co.od",
		"mean.neg.odn",
		"sd.neg.odn",
		"mean.high.odn",
		"sd.high.odn",
		"mean.highdil.odn",
		"sd.highdil.odn",
		"mean.low.odn",
		"sd.low.odn",
		"mean.nsc.odn",
		"sd.nsc.odn",
	]
	missing_ctrl_headers = [h for h in required_ctrl_headers if h not in ctrl_cols]
	if missing_ctrl_headers:
		raise ValueError(
			f"Ctrl sheet is missing expected headers: {', '.join(missing_ctrl_headers)}"
		)

	all_res_cols = header_column_map(all_res_ws)
	if "cutoff" not in all_res_cols:
		all_res_ws.cell(1, all_res_ws.max_column + 1, "Cutoff")
		all_res_cols = header_column_map(all_res_ws)
	required_all_res_headers = [
		"plate",
		"box",
		"sample",
		"comments",
		"mean_sp",
		"res1",
		"res2",
		"res3",
		"res4",
		"type",
		"temp.name",
		"outlier",
		"outlier_log10",
		"disc",
		"cutoff",
		"log10(s/p)",
	]
	missing_all_res_headers = [h for h in required_all_res_headers if h not in all_res_cols]
	if missing_all_res_headers:
		raise ValueError(
			f"all.res sheet is missing expected headers: {', '.join(missing_all_res_headers)}"
		)

	raw_row = next_empty_row(raw_ws)
	ctrl_row = next_empty_row(ctrl_ws)
	all_res_row = next_empty_row(all_res_ws)

	existing_plates: set[str] = set()
	for scan_ws, scan_cols in ((ctrl_ws, ctrl_cols), (all_res_ws, all_res_cols)):
		if "plate" in scan_cols:
			for row_idx in range(2, scan_ws.max_row + 1):
				value = scan_ws.cell(row_idx, scan_cols["plate"]).value
				if isinstance(value, str) and value.strip():
					existing_plates.add(value.strip().upper())

	skipped_plates: List[str] = []

	for input_file in elisa_inputs:
		file_suffix = input_file.suffix.lower()
		if file_suffix != ".xls":
			raise ValueError(f"Unsupported input file type: {input_file.name}")
		plate_results = parse_elisa_export(input_file)

		file_date = extract_date_token(input_file.name)
		if not file_date:
			file_date = extract_date_token(*(pr.plate_full_name for pr in plate_results))
		if not file_date:
			raise ValueError(
				f"Could not detect date token (YY.MM.DD) from file name or plate names in {input_file.name}."
			)
		file_date_uk = format_date_uk(file_date)

		for plate_result in plate_results:
			plate_name = plate_result.plate_short_name
			if plate_name in existing_plates:
				skipped_plates.append(
					f"{plate_name} from {input_file.name} skipped because plate already exists in output workbook."
				)
				continue

			if plate_name not in platemap_layout:
				raise ValueError(
					f"Plate {plate_name} from input file is not present in '{PLATEMAP_SHEET}' sheet."
				)

			entries = platemap_layout[plate_name]
			if not entries:
				continue

			plate_rows: List[Dict[str, object]] = []
			grouped: Dict[Tuple[str, str], Dict[str, object]] = {}
			for entry in entries:
				value_a = plate_result.corrected_by_well.get(entry.well_a)
				value_b = plate_result.corrected_by_well.get(entry.well_b)
				if value_a is None and value_b is None:
					continue

				group_key = (
					entry.sample.strip(),
					str(entry.comments).strip() if entry.comments is not None else "",
				)
				group = grouped.setdefault(
					group_key,
					{
						"plate": plate_name,
						"box": entry.box,
						"sample": entry.sample.strip(),
						"comments": entry.comments,
						"odn_values": [],
					},
				)
				if group["box"] in (None, "") and entry.box not in (None, ""):
					group["box"] = entry.box

				for pos, well_value in ((entry.well_a, value_a), (entry.well_b, value_b)):
					if well_value is None:
						continue
					plate_rows.append(
						{
							"date": file_date_uk,
							"pos": pos,
							"plate": plate_name,
							"box": entry.box,
							"sample": entry.sample,
							"comments": entry.comments,
							"od": well_value,
							"group_key": group_key,
						}
					)

			control_od: Dict[str, List[float]] = {
				"neg": [],
				"high": [],
				"highdil": [],
				"low": [],
				"nsc": [],
			}
			for row_data in plate_rows:
				bucket = control_bucket(str(row_data["sample"]))
				if bucket:
					control_od[bucket].append(float(row_data["od"]))

			mean_nsc_od, _ = mean_and_sd(control_od["nsc"])
			nsc_mean_for_norm = mean_nsc_od if mean_nsc_od is not None else 0.0

			control_odn: Dict[str, List[float]] = {
				"neg": [],
				"high": [],
				"highdil": [],
				"low": [],
				"nsc": [],
			}

			for row_data in plate_rows:
				odn_value = float(row_data["od"]) - nsc_mean_for_norm
				row_data["odn"] = odn_value

				raw_ws.cell(raw_row, raw_cols["date"], row_data["date"])
				raw_ws.cell(raw_row, raw_cols["pos"], row_data["pos"])
				raw_ws.cell(raw_row, raw_cols["plate"], row_data["plate"])
				raw_ws.cell(raw_row, raw_cols["box"], row_data["box"])
				raw_ws.cell(raw_row, raw_cols["sample"], row_data["sample"])
				raw_ws.cell(raw_row, raw_cols["comments"], row_data["comments"])
				raw_ws.cell(raw_row, raw_cols["od"], row_data["od"])
				set_three_decimal(raw_ws.cell(raw_row, raw_cols["od"]))
				raw_ws.cell(raw_row, raw_cols["odn"], odn_value)
				set_three_decimal(raw_ws.cell(raw_row, raw_cols["odn"]))
				raw_row += 1

				bucket = control_bucket(str(row_data["sample"]))
				if bucket:
					control_odn[bucket].append(odn_value)
				group = grouped[row_data["group_key"]]
				group["odn_values"].append(odn_value)

			mean_neg_od, sd_neg_od = mean_and_sd(control_od["neg"])
			mean_high_od, sd_high_od = mean_and_sd(control_od["high"])
			mean_highdil_od, sd_highdil_od = mean_and_sd(control_od["highdil"])
			mean_low_od, sd_low_od = mean_and_sd(control_od["low"])
			mean_nsc_od, sd_nsc_od = mean_and_sd(control_od["nsc"])

			mean_neg_odn, sd_neg_odn = mean_and_sd(control_odn["neg"])
			mean_high_odn, sd_high_odn = mean_and_sd(control_odn["high"])
			mean_highdil_odn, sd_highdil_odn = mean_and_sd(control_odn["highdil"])
			if mean_highdil_odn is None and mean_high_odn is not None:
				mean_highdil_odn = mean_high_odn * 0.453
			mean_low_odn, sd_low_odn = mean_and_sd(control_odn["low"])
			mean_nsc_odn, sd_nsc_odn = mean_and_sd(control_odn["nsc"])

			co_5sd_od = None
			if mean_neg_od is not None and sd_neg_od is not None:
				co_5sd_od = mean_neg_od + 5 * sd_neg_od

			ctrl_ws.cell(ctrl_row, ctrl_cols["date"], file_date_uk)
			ctrl_ws.cell(ctrl_row, ctrl_cols["plate"], plate_name)
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.neg.od"], mean_neg_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.neg.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.neg.od"], sd_neg_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.neg.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.high.od"], mean_high_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.high.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.high.od"], sd_high_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.high.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.highdil.od"], mean_highdil_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.highdil.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.highdil.od"], sd_highdil_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.highdil.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.low.od"], mean_low_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.low.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.low.od"], sd_low_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.low.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.nsc.od"], mean_nsc_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.nsc.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.nsc.od"], sd_nsc_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.nsc.od"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["5sd.co.od"], co_5sd_od)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["5sd.co.od"]))

			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.neg.odn"], mean_neg_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.neg.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.neg.odn"], sd_neg_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.neg.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.high.odn"], mean_high_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.high.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.high.odn"], sd_high_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.high.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.highdil.odn"], mean_highdil_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.highdil.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.highdil.odn"], sd_highdil_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.highdil.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.low.odn"], mean_low_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.low.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.low.odn"], sd_low_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.low.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["mean.nsc.odn"], mean_nsc_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["mean.nsc.odn"]))
			ctrl_ws.cell(ctrl_row, ctrl_cols["sd.nsc.odn"], sd_nsc_odn)
			set_three_decimal(ctrl_ws.cell(ctrl_row, ctrl_cols["sd.nsc.odn"]))
			ctrl_row += 1
			existing_plates.add(plate_name)

			for group in grouped.values():
				type_value = all_res_type_label(plate_name, str(group["sample"]), group["comments"])
				raw_res_values = group["odn_values"][:4]
				qc_res_values, removed_indices = apply_sample_qc(type_value, raw_res_values)
				if len(group["odn_values"]) > 4:
					raise ValueError(
						f"Plate {plate_name} / sample {group['sample']} has more than 4 ODn values; all.res only supports res1-res4."
					)

				mean_sp_value: Optional[float] = None
				log10_sp_value: Optional[float] = None
				if type_value == "s" and mean_neg_odn is not None and mean_highdil_odn is not None:
					sp_denominator = mean_highdil_odn - mean_neg_odn
					if sp_denominator != 0 and qc_res_values:
						sp_values = [
							(odn_value - mean_neg_odn) / sp_denominator
							for odn_value in qc_res_values
						]
						mean_sp_value = statistics.mean(sp_values) + 0.0693
						if mean_sp_value > 0:
							log10_sp_value = math.log10(mean_sp_value)

				all_res_ws.cell(all_res_row, all_res_cols["plate"], plate_name)
				all_res_ws.cell(all_res_row, all_res_cols["box"], group["box"])
				all_res_ws.cell(all_res_row, all_res_cols["sample"], group["sample"])
				all_res_ws.cell(all_res_row, all_res_cols["comments"], group["comments"])
				all_res_ws.cell(all_res_row, all_res_cols["mean_sp"], mean_sp_value)
				set_three_decimal(all_res_ws.cell(all_res_row, all_res_cols["mean_sp"]))

				for idx, value in enumerate(raw_res_values, start=1):
					cell = all_res_ws.cell(all_res_row, all_res_cols[f"res{idx}"])
					cell.value = value
					set_three_decimal(cell)
					if (idx - 1) in removed_indices:
						cell.fill = PINK_FILL

				all_res_ws.cell(all_res_row, all_res_cols["outlier"], None)
				all_res_ws.cell(all_res_row, all_res_cols["outlier_log10"], None)
				all_res_ws.cell(all_res_row, all_res_cols["disc"], True if removed_indices else None)
				all_res_ws.cell(all_res_row, all_res_cols["log10(s/p)"], log10_sp_value)
				set_three_decimal(all_res_ws.cell(all_res_row, all_res_cols["log10(s/p)"]))
				all_res_row += 1

		print(f"Processed: {input_file}")

	if processing_steps.get("all_res", False):
		if outliers_ws is None:
			raise ValueError("all.res processing requires the input outliers sheet")
		populate_all_res_metadata(all_res_ws, all_res_cols)
		populate_outlier_column(all_res_ws, all_res_cols, outliers_ws)
		if "source" in wb.sheetnames:
			source_ws = wb["source"]
			source_cols = source_column_map(source_ws)
			populate_source_conditions(source_ws, source_cols, all_res_ws, all_res_cols)

	if processing_steps.get("cutoff", False):
		cutoff_input_wb = None
		cutoff_outliers_ws = outliers_ws
		if cutoff_outliers_ws is None:
			if not input_workbook.exists():
				raise FileNotFoundError(f"Input workbook does not exist: {input_workbook}")
			cutoff_input_wb = load_workbook(input_workbook, read_only=True, data_only=True)
			if "outliers" not in cutoff_input_wb.sheetnames:
				cutoff_input_wb.close()
				raise ValueError("Input workbook missing required sheet: outliers")
			cutoff_outliers_ws = cutoff_input_wb["outliers"]
		outlier_lookups = build_outlier_lookups(cutoff_outliers_ws)
		build_cutoff_sheet(wb, all_res_ws, all_res_cols, outlier_lookups)
		analyze_cutoff_sheet(wb, all_res_ws, output_workbook.parent / "Cutoff plots")
		if "cutoff" not in wb.sheetnames or "cutoff_log" not in wb.sheetnames:
			raise RuntimeError("Cutoff processing was selected but cutoff sheets were not created.")
		all_res_cols = header_column_map(all_res_ws)
		if "cutoff" not in all_res_cols:
			cutoff_col = all_res_ws.max_column + 1
			all_res_ws.cell(1, cutoff_col, "Cutoff")
			all_res_cols = header_column_map(all_res_ws)
		populate_all_res_cutoff(all_res_ws, wb["cutoff"])
		if cutoff_input_wb is not None:
			cutoff_input_wb.close()

	if processing_steps.get("bootstrap_cutoff", False):
		if "cutoff" not in wb.sheetnames or "cutoff_log" not in wb.sheetnames:
			raise RuntimeError("Bootstrap cutoff analysis requires cutoff processing to be selected.")
		bootstrap_cutoff_analysis(wb, output_workbook.parent / "Cutoff plots")

	if processing_steps.get("move_elisa", False):
		rebuild_positives_and_negatives_sheets(wb, all_res_ws, all_res_cols)

	for input_file in pv_inputs:
		if input_wb is None:
			raise RuntimeError("PV input processing requires the input workbook")
		process_pvnt_file(input_file, input_wb)
		copy_pv_results_to_results_workbook(input_wb, wb)

	if processing_steps.get("pv_res", False):
		rebuild_pv_res_sheet(wb)

	if processing_steps.get("move_pv", False):
		append_pv_runs_to_summaries(wb)

	if processing_steps.get("graphs", False) or processing_steps.get("random_graph", False):
		generate_pv_graphs(wb, random_only=processing_steps.get("random_graph", False))

	for sheet_name in (PLATEMAP_SHEET, "PV.maps", "source", "outliers"):
		if sheet_name in wb.sheetnames:
			del wb[sheet_name]
	output_sheet_order = (RAW_SHEET, CTRL_SHEET, ALL_RES_SHEET, "PV.res", "positives", "negatives", "cutoff", "cutoff_log")
	wb._sheets = [wb[sheet_name] for sheet_name in output_sheet_order if sheet_name in wb.sheetnames]

	if input_wb is not None:
		input_wb.save(input_workbook)
		input_wb.close()
	wb.save(output_workbook)
	print(f"Updated workbook: {output_workbook}")
	if skipped_plates:
		print("Skipped plates:")
		for msg in skipped_plates:
			print(f" - {msg}")


def select_input_files() -> List[Path]:
	import tkinter as tk
	from tkinter import filedialog

	root = tk.Tk()
	root.withdraw()
	selected = filedialog.askopenfilenames(
		title="Select ELISA .xls/.xlsx file(s)",
		filetypes=[
			("Excel files", "*.xls *.xlsx"),
			("XLS files", "*.xls"),
			("XLSX files", "*.xlsx"),
			("All files", "*.*"),
		],
	)
	root.destroy()
	return [Path(p) for p in selected]


def parse_args() -> argparse.Namespace:
	parser = argparse.ArgumentParser(
		description=(
			"Process ELISA .xls exports, calculate (450-620), write mapped values to 'raw', "
			"and control statistics to 'ctrl' in results.xlsx."
		)
	)
	parser.add_argument(
		"inputs",
		nargs="*",
		type=Path,
		help="Optional .xls input files. If omitted, a file picker opens.",
	)
	parser.add_argument(
		"--input-workbook",
		type=Path,
		default=DEFAULT_INPUT_XLSX,
		help=f"Input workbook containing platemaps, PV.maps, source, and outliers (default: {DEFAULT_INPUT_XLSX})",
	)
	parser.add_argument(
		"--output",
		type=Path,
		default=DEFAULT_OUTPUT_XLSX,
		help=f"Output workbook path (default: {DEFAULT_OUTPUT_XLSX})",
	)
	parser.add_argument(
		"--metadata-workbook",
		type=Path,
		default=DEFAULT_METADATA_XLSX,
		help=f"DSS metadata workbook containing the meta sheet (default: {DEFAULT_METADATA_XLSX})",
	)
	return parser.parse_args()


def prompt_processing_steps() -> Dict[str, bool]:
	steps = (
		("all_res", "Process all.res sheet?"),
		("cutoff", "Process cutoff sheet and cutoff_log sheet?"),
		("bootstrap_cutoff", "Bootstrap cutoff?"),
		("move_elisa", "Move ELISA results to positives/negatives?"),
		("pv_res", "Process PV.res sheet?"),
		("move_pv", "Move PV results to positives/negatives?"),
		("graphs", "Regenerate PV neutralisation graphs?"),
		("random_graph", "Generate one random PV graph?"),
	)
	try:
		import tkinter as tk

		root = tk.Tk()
		root.title("ELISA/PV processing steps")
		variables = {key: tk.BooleanVar(value=False) for key, _ in steps}
		tk.Label(root, text="Select processing steps to run:").pack(anchor="w", padx=12, pady=(12, 6))
		for key, label in steps:
			tk.Checkbutton(root, text=label, variable=variables[key]).pack(anchor="w", padx=18, pady=2)
		result: Dict[str, bool] = {}
		def accept() -> None:
			result.update({key: bool(variables[key].get()) for key, _ in steps})
			root.destroy()
		tk.Button(root, text="Continue", command=accept).pack(pady=12)
		root.protocol("WM_DELETE_WINDOW", accept)
		root.mainloop()
		return result or {key: False for key, _ in steps}
	except Exception:
		return {key: False for key, _ in steps}


def main() -> None:
	args = parse_args()
	input_files = args.inputs or select_input_files()
	if not input_files:
		print("No input files selected; refreshing existing workbook only.")
	processing_steps = prompt_processing_steps()

	for path in input_files:
		if not path.exists():
			raise FileNotFoundError(f"Input file not found: {path}")

	process_files(
		input_files,
		args.input_workbook,
		args.output,
		metadata_workbook=args.metadata_workbook,
		processing_steps=processing_steps,
	)


if __name__ == "__main__":
	main()
