def compute_call_value(out_values: Sequence[object]) -> str:
	"""Compute Call value from all out[i] values for a sample row."""
	low_set = {0.001, 0.01}
	parsed_values: List[float] = []
	for value in out_values:
		if value in (None, ""):
			continue
		value_text = str(value).strip().lower()
		parsed_float = _try_parse_float(value_text)
		if parsed_float is not None:
			parsed_values.append(parsed_float)

	low_count = sum(1 for value in parsed_values if value in low_set)
	high_count = sum(1 for value in parsed_values if value == 0.1)

	if low_count >= 2:
		return "pos.high"
	if low_count == 1 and high_count >= 1:
		return "pos.low"
	if high_count >= 2:
		return "equiv.high"
	return "equiv.low"


