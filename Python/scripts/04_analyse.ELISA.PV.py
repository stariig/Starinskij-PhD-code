def normalize_well(w: object) -> Optional[str]:
	if w is None:
		return None
	s = str(w).strip().upper()
	# Normalize forms like A01 -> A1, remove spaces
	m = re.match(r"^([A-H])\s*0*(\d{1,2})$", s)
	if m:
		return f"{m.group(1)}{int(m.group(2))}"
	# If already like 'A1'
	m2 = re.match(r"^([A-H])\s*(\d{1,2})$", s)
	if m2:
		return f"{m2.group(1)}{int(m2.group(2))}"
	return s


