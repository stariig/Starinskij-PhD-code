def bootstrap_cutoff_analysis(wb, output_dir: Path, bootstrap_count: int = 10000) -> None:
	import numpy as np

	rng = np.random.default_rng(20260912)
	def gaussian_cutoff(sample) -> float:
		mean_value, sd_value = mean_and_sd(sample.tolist())
		return mean_value + 3 * sd_value

	methods = (
		("CO_Gaus", gaussian_cutoff),
		("CO_P99.5", lambda sample: float(np.percentile(sample, 99.5))),
		("CO_P99", lambda sample: float(np.percentile(sample, 99.0))),
		("CO_P97.5", lambda sample: float(np.percentile(sample, 97.5))),
		("CO_PO95", lambda sample: float(np.percentile(sample, 95.0))),
	)
	reports: List[str] = []
	for sheet_name, dataset_name, outlier_header, report_name in (
		("cutoff", "linear", "outlier", "linear_cutoff_results.txt"),
		("cutoff_log", "log10", "outlier_log10", "log10_cutoff_results.txt"),
	):
		if sheet_name not in wb.sheetnames:
			continue
		ws = wb[sheet_name]
		columns = header_column_map(ws)
		if "mean_sp1" not in columns or outlier_header not in columns:
			continue
		clean_values = [
			value
			for row in range(2, ws.max_row + 1)
			if (value := _try_parse_float(ws.cell(row, columns["mean_sp1"]).value)) is not None
			and ws.cell(row, columns[outlier_header]).value in (None, "")
		]
		if not clean_values:
			reports.append(f"{dataset_name} bootstrap cutoff analysis: no clean Mean_SP1 values.")
			continue
		values = np.asarray(clean_values, dtype=float)
		bootstrap_cutoffs = {name: np.empty(bootstrap_count, dtype=float) for name, _ in methods}
		for index in range(bootstrap_count):
			sample = rng.choice(values, size=values.size, replace=True)
			for method_name, calculate in methods:
				bootstrap_cutoffs[method_name][index] = calculate(sample)
		reports.append(f"{dataset_name} bootstrap cutoff analysis (n={len(clean_values)}, iterations={bootstrap_count})")
		for method_name, _ in methods:
			low, high = np.percentile(bootstrap_cutoffs[method_name], (2.5, 97.5))
			reports.append(f"{method_name}: CI95={low:.3f},{high:.3f}")
		with (output_dir / report_name).open("a", encoding="utf-8") as report:
			report.write("\n" + "\n".join(reports[-(len(methods) + 1):]) + "\n")


