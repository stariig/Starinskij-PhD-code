def normalize_temp_name(text: object) -> str:
	if text is None:
		return ""
	text = str(text).replace("\xa0", " ").replace("\u202f", " ").replace("\u2007", " ")
	return re.sub(r"\s+", " ", text).strip()


def canonical_lookup_key(text: object) -> str:
	"""Normalize text keys for case-insensitive workbook lookups."""
	return normalize_temp_name(text).lower()


def contains_non_200_dilution(text: object) -> bool:
	if not isinstance(text, str):
		return False
	for match in re.finditer(r"1\s*:\s*(\d+)", text):
		if int(match.group(1)) != 200:
			return True
	return False


